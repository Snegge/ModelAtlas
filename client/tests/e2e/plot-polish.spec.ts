import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

test("plot states, point selection and compact preview close", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/");
  await page.getByRole("button", { name: "Plot", exact: true }).click();
  await expect(page.locator(".plot-empty")).toBeVisible();
  await page.getByLabel("GPU profile (searchable)").fill("NVIDIA GeForce RTX 3060 · 12 GB");
  await page.getByLabel("GPU profile (searchable)").press("Tab");
  await page.getByLabel("System RAM · GiB (0–1024)").fill("48");
  await page.getByLabel("Search model or provider").fill("SmolLM2-1.7B-Instruct");
  const point = page.locator(".plot-dot");
  await expect(point).toHaveCount(1);
  await expect(page.locator(".plot-empty")).toHaveCount(0);
  await point.focus();
  await page.keyboard.press("Enter");
  await expect(point).toHaveAttribute("aria-pressed", "true");
  const close = page.getByRole("button", { name: "Close preview", exact: true });
  await expect(close).toHaveText("");
  await close.click();
  await expect(page.locator(".preview")).toHaveCount(0);
  await expect(point).toHaveAttribute("aria-pressed", "false");
  await page.locator(".plot-heading").scrollIntoViewIfNeeded();
  expect((await new AxeBuilder({ page }).include(".catalog-workspace").analyze()).violations).toEqual([]);
  await page.screenshot({ path: "test-results/plot-polished.png" });
  await page.getByRole("button", { name: "Bars", exact: true }).click();
  await page.locator(".score-row").click();
  const panel = (await page.locator(".preview").boundingBox())!;
  const button = (await close.boundingBox())!;
  expect(Math.abs(panel.x + panel.width - button.x - button.width - 9)).toBeLessThan(2);
  expect(Math.abs(button.y - panel.y - 9)).toBeLessThan(2);
  await close.click();
  await expect(page.locator(".preview")).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Plot", exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator(".plot-scroll").scrollIntoViewIfNeeded();
  await page.screenshot({ path: "test-results/plot-polished-mobile.png" });
});
